def all_keys() -> set[str]:
    return set(TEXTS["en"])


def required_glyphs() -> set[str]:
    glyphs = {chr(code) for code in range(32, 127)}
    for text in TEXTS["zh"].values():
        glyphs.update(text)
    return glyphs


def tr(language: str, key: str, **kwargs) -> str:
    text = TEXTS.get(language, {}).get(key)
    if text is None:
        text = TEXTS["en"].get(key)
        if text is None:
            warnings.warn(
                f"missing translation key: {key}",
                RuntimeWarning,
                stacklevel=2,
            )
            return key
        if language in TEXTS:
            warnings.warn(
                f"missing {language} translation for {key}; using English",
                RuntimeWarning,
                stacklevel=2,
            )
    try:
        return text.format(**kwargs)
    except (KeyError, IndexError, ValueError):
        warnings.warn(
            f"invalid format for translation key: {key}",
            RuntimeWarning,
            stacklevel=2,
        )
        return text
